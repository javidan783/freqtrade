from freqtrade.strategy import IStrategy, DecimalParameter
from pandas import DataFrame
import talib.abstract as ta

class PassivbotStyleStrategy(IStrategy):
    """
    Generated by CodePen Generator - Completed Version
    Strategy based on Passivbot Trailing Martingale logic.
    """
    
    INTERFACE_VERSION = 3

    timeframe = '1h'
    can_short = True
    max_open_trades = 1
    
    # پارامترهای استراتژی (با قابلیت بهینه‌سازی در Hyperopt)
    grid_spacing = DecimalParameter(0.01, 0.05, default=0.02, space="buy")
    initial_qty = DecimalParameter(0.001, 0.01, default=0.002, space="buy")
    close_profit = DecimalParameter(0.001, 0.02, default=0.005, space="sell")
    martingale = DecimalParameter(1.0, 2.0, default=1.5, space="buy")
    max_dca = 5

    def populate_indicators(self, dataframe: DataFrame, metadata: dict) -> DataFrame:
        dataframe['ema_fast'] = ta.EMA(dataframe, timeperiod=12)
        dataframe['ema_slow'] = ta.EMA(dataframe, timeperiod=96)
        return dataframe

    def populate_entry_trend(self, dataframe: DataFrame, metadata: dict) -> DataFrame:
        # منطق ورود اولیه
        dataframe.loc[
            (dataframe['ema_fast'] > dataframe['ema_slow']),
            'enter_long'] = 1
        dataframe.loc[
            (dataframe['ema_fast'] < dataframe['ema_slow']),
            'enter_short'] = 1
        return dataframe

    def populate_exit_trend(self, dataframe: DataFrame, metadata: dict) -> DataFrame:
        # منطق خروج (در این استراتژی، خروج بیشتر بر عهده مدیریت ریسک است)
        return dataframe

    def adjust_trade_position(self, trade, current_time, current_rate, 
                              current_profit, min_stake, max_stake, 
                              current_entry_rate, current_exit_rate, 
                              current_entry_profit, current_exit_profit, **kwargs):
        """
        منطق DCA / Martingale (قلب استراتژی Passivbot)
        """
        # بررسی می‌کنیم که آیا قیمت به اندازه فاصله گرید افت کرده است؟
        if current_profit < -self.grid_spacing.value:
            
            # بررسی می‌کنیم که آیا تعداد دفعات ورود مجدد از حد مجاز عبور نکرده است؟
            if trade.nr_of_successful_entries < self.max_dca:
                
                # محاسبه حجم جدید بر اساس ضریب مارتینگل
                new_stake = trade.stake_amount * self.martingale.value
                
                # اطمینان از اینکه حجم جدید در محدوده مجاز صرافی باشد
                if min_stake <= new_stake <= max_stake:
                    return new_stake
                    
        return None
